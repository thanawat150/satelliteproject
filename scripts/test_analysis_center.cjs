/* Evidence-driven dashboard guardrails: no fabricated raster or cross-date province totals. */
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const sandbox={window:{}};
vm.runInNewContext(read('docs/analysis-center.js'),sandbox,{filename:'analysis-center.js'});
const model=sandbox.window.AnalysisCenter.model;
assert(model&&typeof model.makePlot==='function');
const history=JSON.parse(read('docs/data/analysis_history.json'));
const data=JSON.parse(read('docs/data/plots.json'));
const geo=JSON.parse(read('docs/data/boundaries.geojson'));
assert.equal(data.plots.length,19);
assert.equal(geo.features.length,19);
const plotIds=new Set(data.plots.map(p=>p.plot));
assert([...plotIds].every(id=>geo.features.some(f=>f.properties.plot===id)),'Every monitored plot needs a real PDD boundary');
assert([...plotIds].every(id=>history.plots[id]),'Every plot needs QA history');
const p13=data.plots.find(p=>p.plot==='13-STC');
const defaults=model.plotDefaults(history,p13,[]);
assert.equal(defaults[0],'2026-04-30');
assert.equal(defaults[1],'2026-09-29');
assert.equal(defaults[2],'2026-10-07');
const compare=model.makePlot(history,p13,defaults);
assert.equal(compare.records[2].analysis_status,'PARTIAL');
assert.equal(compare.paired,true);
assert(compare.change>190&&compare.change<200);
const unsafe=model.makePlot(history,p13,['2026-09-29','2026-10-07','2026-04-30']);
assert.equal(unsafe.paired,false,'PARTIAL cannot be promoted to a verified comparison');
assert.equal(unsafe.change,null);
const provinceDates=model.provinceDefaults(history,data.plots);
const province=model.makeProvince(history,data.plots,provinceDates);
assert.equal(province.items.length,19);
assert(province.covered>=1&&province.covered<=19);
assert(province.paired<=province.covered);
assert(province.missing===19-province.covered);
const sumCurrent=province.items.filter(x=>x.goodB).reduce((s,x)=>s+x.rb.water_rai,0);
assert.equal(province.areaWater,sumCurrent);
const sumPair=province.items.filter(x=>x.goodA&&x.goodB).reduce((s,x)=>s+(x.rb.water_rai-x.ra.water_rai),0);
assert.equal(province.change,province.paired?sumPair:null);
assert.equal(model.qa(null),'INDEX_PENDING');
assert.equal(model.qa({analysis_status:'PARTIAL'}),'PARTIAL');
assert.equal(model.trusted({analysis_status:'AUTO_VALID',valid_pct:69}),false);
assert.equal(model.trusted({analysis_status:'AUTO_VALID',valid_pct:70}),true);
vm.runInNewContext(read('docs/three-period-report.js'),sandbox,{filename:'three-period-report.js'});
assert.equal(sandbox.window.ThreePeriodReport.setDates('13-STC',defaults),true);
assert.equal(sandbox.window.ThreePeriodReport.setDates('13-STC',['2026-04-30','2026-04-30','']),false);
const html=read('docs/index.html');
for(const id of ['tab-center','mc-scope-province','mc-scope-plot','mc-mode-auto','mc-mode-manual','mc-date-a','mc-date-b','mc-date-c','mc-results','mc-map','mc-data','mc-plot','mc-chart','mc-preview']){
 assert(html.includes('id="'+id+'"'),id+' must exist');
}
assert(html.includes('analysis-center.js?v=')&&html.includes('analysis-center.css?v='));
const app=read('docs/app.js');
assert(app.includes('AnalysisCenter?.init?.'));
assert(app.includes("window.AnalysisCenter?.showTab?.(tab)"));
assert(app.includes("window.AnalysisCenter?.onPlotChange?.(p)"));
console.log('Monitoring Center QA tests PASS: 19 PDD polygons, verified-only comparisons, manual PARTIAL guard, province same-date aggregation, report date linking and DOM wiring');
